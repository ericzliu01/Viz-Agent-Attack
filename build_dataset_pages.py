def scatter_analyze(ds):
    xs = ds["x"]["values"]
    n = len(xs)
    need(len(ds["series"]) == 2 and n >= 6, ds, "scatter needs 2 series over >= 6 x values")
    s1, s2 = (s["values"] for s in ds["series"])
    need(len(s1) == n and len(s2) == n, ds, "each scatter series needs one value per x value")
    need(all(a < b for a, b in zip(xs, xs[1:])), ds, "x values must increase")
    need(all(a < b for a, b in zip(s1, s1[1:])), ds, "series 1 must strictly rise")
    need(all(a > b for a, b in zip(s2, s2[1:])), ds, "series 2 must strictly fall")
    diffs = [abs(a - b) for a, b in zip(s1, s2)]
    closest = diffs.index(min(diffs))
    need(min(diffs) <= 0.6 * sorted(diffs)[1], ds, "one x must be clearly where the series are closest")
    everything = s1 + s2
    return {"closest": closest, "s2_min": s2.index(min(s2)),
            "lo": nice_floor(min(everything) * 0.85), "hi": nice_ceil_fine(max(everything) * 1.03),
            "wide_hi": nice_ceil(max(everything) * 2.9)}


