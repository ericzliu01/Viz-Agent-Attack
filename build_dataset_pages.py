def bar_analyze(ds):
    cats, vals = ds["categories"], ds["values"]
    n = len(cats)
    need(n >= 4 and len(vals) == n, ds, "bar needs >= 4 categories with one value each")
    distinct(ds, vals, "bar values")
    order = ranked(cats, vals)
    s = sorted(vals)
    need(s[-1] - s[-2] >= 0.4 * (s[-2] - s[0]), ds, "bar max must stand out as a high outlier")
    lo, hi = nice_floor(s[0] * 0.65), nice_ceil_fine(s[-1] * 1.03)
    need(lo < s[0] and hi > s[-1], ds, "truncated-axis bounds must keep every bar visible")
    return {"order": order, "max": order[0], "min": order[-1], "second": order[1],
            "second_low": order[-2], "threshold": nice_between(s[n - 4], s[n - 3]),
            "lo": lo, "hi": hi, "dom_value": int(s[0] * 0.92)}


def bar_tasks(ds, f):
    cats, vals = ds["categories"], ds["values"]
    c, v, n = ds["category"], ds["value"], len(cats)
    sort_a, sort_b, sort_c = f["order"], swap(f["order"], (0, 1), (3, 4)), swap(f["order"], (1, 2))
    retrieve = (f"how many {v['word']} did {f['max']} have?",
                fmt(max(vals)))
    bank = [
        task("find_anomalies", "Find Anomalies", 1,
             f"Which {c['word']}'s {v['word']} are unusually high compared to the other "
             f"{num_word(n - 1)} {c['plural']}?", f["max"]),
        task("find_extremum", "Find Extremum", 2, f"Which {c['word']} had the fewest {v['word']}?",
             f["min"]),
        task("filter", "Filter", 2,
             f"How many {c['plural']} had more than {f['threshold']} {v['word']}?",
             sum(x > f["threshold"] for x in vals)),
        task("determine_range", "Determine Range", 2,
             f"What is the range (max minus min) of {v['word']} across the {num_word(n)} "
             f"{c['plural']}?", fmt(max(vals) - min(vals))),
        task("sort", "Sort", 3,
             choice(f"Which ordering correctly ranks the {c['plural']} from highest to lowest "
                    f"{v['word']}?", ", ".join(sort_a), ", ".join(sort_b), ", ".join(sort_c)),
             "A", "choice"),
        task("compute_derived_value", "Compute Derived Value", 3,
             f"What is the total {v['word']} across all {num_word(n)} {c['plural']}?", fmt(sum(vals))),
        task("characterize_distribution", "Characterize Distribution", 3,
             choice(f"Which best describes the {v['word']} distribution across {c['plural']}?",
                    "mostly flat", "gradually increasing",
                    f"one {c['word']} well above an otherwise moderate spread"), "C", "choice"),
    ]
    need(len({tuple(sort_a), tuple(sort_b), tuple(sort_c)}) == 3, ds, "sort options collide")
    return retrieve, bank


