# ---------- page rewriting ----------

def page_fragments(chart_type, ds, f, attack):
    _, _, fragments, attack_fragments, _, _ = SPECS[chart_type]
    title = ds["title"]
    out = [f"<title>{title} - ", f"<h2>{title}</h2>", f'<p class="subtitle">{ds["subtitle"]}</p>']
    out += list(fragments(ds, f).values())
    if attack is not None:
        out += attack_fragments(ds, f)[attack]
    return out


def rename_tokens(text, mapping):
    """Swap whole identifier/word tokens, including camelCase compounds such
    as traceMobile or mobileValues."""
    caps = {k: v for k, v in mapping.items() if k[:1].isupper()}
    lowers = {k: v for k, v in mapping.items() if k[:1].islower()}

    def swap_token(match):
        word = match.group(0)
        if word in mapping:
            return mapping[word]
        for old, new in caps.items():
            prefix = word[: -len(old)]
            if word.endswith(old) and prefix and prefix.islower():
                return prefix + new
        for old, new in lowers.items():
            rest = word[len(old):]
            if word.startswith(old) and rest[:1].isupper():
                return new + rest
        return word

    return TOKEN.sub(swap_token, text)


def rewrite_page(text, chart_type, template, tf, ds, f, attack):
    old = page_fragments(chart_type, template, tf, attack)
    new = page_fragments(chart_type, ds, f, attack)
    pairs = sorted(zip(old, new), key=lambda p: -len(p[0]))
    slots = []
    for i, (o, n) in enumerate(pairs):
        if o in text:
            text = text.replace(o, f"\x00{i}\x00")
            slots.append(i)
    tokens = SPECS[chart_type][4]
    mapping = {o: n for o, n in zip(tokens(template).values(), tokens(ds).values()) if o != n}
    text = rename_tokens(text, mapping)
    for i in slots:
        text = text.replace(f"\x00{i}\x00", pairs[i][1])
    return text, {pairs[i][0] for i in slots}


YEAR_AXIS = {
    "d3": ('d3.axisBottom(x).tickSize(0)', 'd3.axisBottom(x).tickSize(0).tickFormat(d3.format("d"))'),
    "chartjs": ('ticks: { color: inkMuted', 'ticks: { callback: (v) => String(v), color: inkMuted'),
    "plotly": ('xaxis: { title', 'xaxis: { tickformat: "d", title'),
}


def year_axis(text, library, ds):
    """A scatter whose x values are years: print them without a thousands
    separator, and in Vega-Lite drop the zero baseline that would squash
    every point against the right edge. Only the x axis (the first match
    in each page) is changed."""
    if library == "vega-lite":
        old = f'type: "quantitative", title: {js(ds["x"]["axis_title"])},'
        new = old + ' scale: { zero: false },'
        anchor = "labelFontSize: 12"
        need(old in text, ds, "vega-lite scatter x encoding not found for the year axis")
        text = text.replace(old, new, 1)
        start = text.index(new)
        at = text.index(anchor, start)
        return text[:at] + 'format: "d", ' + text[at:]
    old, new = YEAR_AXIS[library]
    need(old in text, ds, f"{library} scatter x axis not found for the year axis")
    return text.replace(old, new, 1)


def is_year_axis(chart_type, ds):
    xs = ds.get("x", {}).get("values") if chart_type == "scatter" else None
    return bool(xs) and all(float(v).is_integer() and 1000 <= v <= 2999 for v in xs)


def check_tokens(chart_type, template, ds, templates_text):
    """New words used as identifiers must be safe and must not collide with
    words the template pages already use."""
    tokens = SPECS[chart_type][4]
    used = set(TOKEN.findall(templates_text))
    old_words = tokens(template)
    for role, word in tokens(ds).items():
        need(IDENTIFIER.match(word) and word not in JS_RESERVED, ds,
             f"{role} {word!r} must be a single identifier-safe word")
        need(word == old_words[role] or word not in used, ds,
             f"{role} {word!r} collides with a word the template pages already use")
    need(len(set(tokens(ds).values())) == len(tokens(ds)), ds, "identifier words must all differ")


def leaked_words(chart_type, template, ds, text):
    """Template-only names or words still present in a generated page."""
    tokens = SPECS[chart_type][4]
    names = template["categories"] if chart_type == "bar" else [s["name"] for s in template["series"]]
    new_words = set(TOKEN.findall(json.dumps(ds))) | set(json.dumps(ds).split('"'))
    candidates = set(tokens(template).values()) | set(names)
    present = set(TOKEN.findall(text)) | {n for n in names if " " in n and n in text}
    return sorted(w for w in candidates & present if w not in new_words)


