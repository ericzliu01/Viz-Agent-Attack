# ---------- small helpers ----------

def num_word(n):
    return NUMBER_WORDS.get(n, str(n))


def js(value):
    return json.dumps(value, ensure_ascii=False)


def fmt(value):
    value = round(float(value), 6)
    return str(int(value)) if value.is_integer() else str(value)


def choice(question, *options):
    return build_reasoning_pages.choice(question, *options)


def swap(seq, *pairs):
    out = list(seq)
    for i, j in pairs:
        out[i], out[j] = out[j], out[i]
    return out


def dips(values):
    return [i for i in range(1, len(values)) if values[i] < values[i - 1]]


def pearson(xs, ys):
    n = len(xs)
    mx, my = sum(xs) / n, sum(ys) / n
    cov = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
    sx = math.sqrt(sum((x - mx) ** 2 for x in xs))
    sy = math.sqrt(sum((y - my) ** 2 for y in ys))
    return cov / (sx * sy)


def nice_floor(v):
    step = 10 ** math.floor(math.log10(v))
    return int(math.floor(v / step) * step)


def nice_ceil(v):
    step = 10 ** math.floor(math.log10(v))
    return int(math.ceil(v / step) * step)


def nice_ceil_fine(v):
    step = 10 ** max(math.floor(math.log10(v)) - 1, 0)
    return int(math.ceil(v / step) * step)


def nice_between(lo, hi):
    """A round threshold strictly between lo and hi."""
    exp = math.floor(math.log10(hi))
    for e in range(exp, exp - 6, -1):
        for step in (10 ** e, 5 * 10 ** (e - 1)):
            t = (math.floor(lo / step) + 1) * step
            if lo < t < hi:
                return int(t) if float(t).is_integer() else t
    raise ValueError(f"no threshold between {lo} and {hi}")


def ranked(labels, values):
    return [labels[i] for i in sorted(range(len(values)), key=lambda i: -values[i])]


def need(cond, ds, message):
    if not cond:
        raise ValueError(f"{ds.get('id')}: {message}")


def distinct(ds, values, what):
    need(len(set(values)) == len(values), ds, f"{what} must be distinct")


def task(task_id, category, tier, question, truth, answer_type=None):
    entry = {"task_id": task_id, "task_category": category, "tier": tier,
             "question": question, "ground_truth": str(truth)}
    if answer_type:
        entry["answer_type"] = answer_type
    return entry


def series_id(name):
    words = re.findall(r"[A-Za-z0-9]+", name)
    return words[0].lower() + "".join(w[:1].upper() + w[1:] for w in words[1:])


