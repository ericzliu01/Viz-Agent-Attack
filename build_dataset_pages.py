"""Generate extra datasets for every chart type: clean pages, capability
tasks, and a copy of every attack, from datasets/corpus_datasets.json.

The hand-written pages (pages/<library>/clean_<type>.html and
attack_<type>_<attack>.html) stay as they are and serve as templates.
datasets/templates.json records the data and wording those pages use; for
each dataset in corpus_datasets.json this script swaps that data and wording
into every template page, recomputes the numbers the attacks inject (axis
bounds, false claims, decoy targets) from the new values, and recomputes
every capability-task question and ground truth. The revenue chart type has
its own generator, build_reasoning_pages.build(), which is called here too.

Writes, per library under pages/<library>/, for each dataset <id>:
  clean_<type>__<id>.html / .meta.json / .capability_tasks.json
  attack_<type>_<attack>__<id>.html / .meta.json
Generated files are exactly the "__" files; each run deletes the old ones
first, so changing the data is: edit (or swap in) the JSON file, then rerun
this script. corpus_datasets.json is computed from the CSVs by
datasets/build_corpus_datasets.py (climate, public_health and steam views
that meet the shape rules below; revenue keeps the dummy entries).
datasets/dummy_datasets.json holds the earlier placeholder data.

Shape rules (checked; a dataset that breaks one raises ValueError, because
an attack or task premise would no longer hold):
  bar          >= 4 categories, distinct values, one clearly high outlier
  line         2 series over >= 5 x labels; series 1 rises overall with at
               least one dip; series 2 rises with exactly one dip and peaks
               at a different x label than series 1
  scatter      2 series over increasing x; series 1 strictly rises, series 2
               strictly falls, one x where they are clearly closest
  stacked_bar  3 series over >= 4 categories; series 1 has exactly one dip,
               totals strictly rise, series 2 rises
  revenue      see build_reasoning_pages.analyze()
The real datasets (datasets/real_datasets.json with tasks/extended_tasks.json)
are generated by build_real_dataset_pages.build_all(), called last.
Words that the pages use as JavaScript identifiers (category/value words,
line and stacked-bar series names) must be single identifier-safe words.

Usage: python build_dataset_pages.py [--datasets datasets/corpus_datasets.json]
"""
