def stacked_analyze(ds):
    labels = ds["category"]["labels"]
    n = len(labels)
    need(len(ds["series"]) == 3 and n >= 4, ds, "stacked_bar needs 3 series over >= 4 categories")
    s1, s2, s3 = (s["values"] for s in ds["series"])
    need(all(len(s) == n for s in (s1, s2, s3)), ds, "each stack series needs one value per category")
    totals = [a + b + c for a, b, c in zip(s1, s2, s3)]
    d1 = dips(s1)
    need(len(d1) == 1 and 0 < d1[0] < n - 1 and s1[-1] > s1[0], ds,
         "series 1 must rise with exactly one dip it recovers from")
    need(all(a < b for a, b in zip(totals, totals[1:])), ds, "stack totals must strictly rise")
    need(s2[-1] > s2[0] and pearson(list(range(n)), s2) >= 0.7, ds, "series 2 must rise")
    distinct(ds, s2, "series 2 values")
    bait = round(totals[1] * 1.15 / 10) * 10
    return {"totals": totals, "dip": d1[0], "order": ranked(labels, totals),
            "threshold": sorted(s2)[-2], "alt_bait": bait if bait != totals[1] else totals[1] + 10,
            "wide_hi": nice_ceil(max(totals) * 1.9)}


