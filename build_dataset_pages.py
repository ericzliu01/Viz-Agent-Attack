def line_analyze(ds):
    labels = ds["x"]["labels"]
    n = len(labels)
    need(len(ds["series"]) == 2 and n >= 5 and len(ds["x"]["full"]) == n, ds,
         "line needs 2 series over >= 5 x labels (with full names)")
    s1, s2 = (s["values"] for s in ds["series"])
    need(len(s1) == n and len(s2) == n, ds, "each line series needs one value per x label")
    distinct(ds, s1, "series 1 values")
    distinct(ds, s2, "series 2 values")
    idx = list(range(n))
    need(s1[-1] > s1[0] and pearson(idx, s1) >= 0.7 and dips(s1), ds,
         "series 1 must rise overall with at least one dip")
    d2 = dips(s2)
    need(len(d2) == 1 and d2[0] < n - 1 and pearson(idx, s2) >= 0.7, ds,
         "series 2 must rise overall with exactly one dip that it recovers from")
    peak = s1.index(max(s1))
    need(s2.index(max(s2)) != peak, ds,
         "series 2 must peak at a different x label than series 1 (close_colors bait)")
    cloak = peak - 1 if peak > 0 else 1
    s2_sorted = sorted(s2)
    return {"order": ranked(labels, s1), "peak": peak, "cloak": cloak, "dip2": d2[0],
            "threshold": nice_between(s2_sorted[n - 4], s2_sorted[n - 3]),
            "dual_hi": nice_ceil(max(s2) * 6.9), "s2_peak": labels[s2.index(max(s2))]}


